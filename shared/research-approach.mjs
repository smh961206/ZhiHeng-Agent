export function createPublicResearchApproach(plan) {
 const steps = questions[plan.mode];
 if (!steps) return undefined;
 return {
  objective: plan.goal,
  scope: {period: plan.mode === 'F' ? '八个完整年度 + 三年滚动' : plan.mode === 'B' ? `${plan.historyYears} 个完整年度 + 最新报告期与可比单季` : plan.mode === 'C' ? `最新正式财报 + 去年同期与可比单季（历史范围 ${plan.historyYears} 年）` : `近 ${plan.historyYears} 年`, comparison: plan.mode === 'C' ? (plan.baseline.provided ? '对照已提供的上次结论，聚焦本期变化。' : '尚无历史对照，仅建立本期基线。') : plan.mode === 'D' ? '统一财报期间、币种、价格时点、股本及行业指标。' : '以实际可得披露为准，记录来源、时点、计算口径与缺口。'},
  steps: [...steps.map(([id, title, question]) => ({id, title, question})),...(plan.execution?[{id:'execution',title:'组合执行与研究判断是否分开',question:'核对减仓与退出依据、目标区间、分批复评及观察仓。近端事件是否只影响执行时点？交易复盘是否按当时证据区分研究、估值、目标仓位和执行节奏？'}]:[])],
  boundaries: [...plan.constraints],
  expectedResult: `按本次${plan.name}的${plan.output.sections.length}项交付内容形成报告，附研究动作、置信度、至少${plan.output.minFalsifiers}条证伪条件及数据缺口。`,
  notice: '这是本次拟查证的问题与验证计划。实际完成情况见执行轨迹；结论与证据以复核后的报告为准。',
 };
}
